# Usage: python3 tools/gen_opus_tables.py path/to/libopus > src/codecs/opus/tables.rs
# libopus 1.4: https://github.com/xiph/opus (BSD-3-Clause, Apache-2.0 compatible).
#
# Converts the normative tables of RFC 6716 that libopus carries (CELT band
# layout, allocation table, energy models, pulse cache; SILK codebooks,
# iCDFs, pitch and LTP tables, resampler coefficients) into Rust constants.
# The CELT tables are the float build's (`static_modes_float.h`).
import re, sys, os

root = sys.argv[1]


def load(rel):
    s = open(os.path.join(root, rel)).read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def body(src, name, nth=0):
    ms = list(re.finditer(r'\b' + re.escape(name) + r'\s*((?:\[[^\]]*\])*)\s*=\s*\{', src))
    assert ms, name
    m = ms[nth]
    i = m.end()
    depth = 1
    while depth:
        c = src[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    return src[m.end():i - 1]


# Integer #defines used inside table initialisers (e.g. OFFSET_VL_Q10).
MACROS = {}
for header in ['silk/define.h', 'silk/tuning_parameters.h', 'silk/resampler_rom.h']:
    for m in re.finditer(r'#define\s+(\w+)\s+([^\n]+)', load(header)):
        MACROS[m.group(1)] = m.group(2).strip()


def value(token):
    try:
        return int(token, 0)
    except ValueError:
        expr = token
        for _ in range(8):
            expr = re.sub(r'\b[A-Z_][A-Z0-9_]*\b', lambda m: '(' + MACROS.get(m.group(0), m.group(0)) + ')', expr)
        return int(eval(expr))


def ints(src, name, nth=0):
    b = body(src, name, nth)
    return [value(t) for t in re.split(r'[\s,{}]+', b) if t.strip()]


def floats(src, name, nth=0):
    b = body(src, name, nth)
    out = []
    for t in re.split(r'[\s,{}]+', b):
        t = t.strip()
        if not t:
            continue
        t = t.rstrip('fF')
        out.append(float(eval(t)))
    return out


