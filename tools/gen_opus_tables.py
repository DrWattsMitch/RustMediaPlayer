def emit(rust, ty, values, doc, per_line=16):
    lines.append(f"/// {doc}")
    lines.append(f"pub static {rust}: [{ty}; {len(values)}] = [")
    for k in range(0, len(values), per_line):
        chunk = values[k:k + per_line]
        if ty == 'f32':
            lines.append("\t" + ", ".join(repr(float(v)) for v in chunk) + ",")
        else:
            lines.append("\t" + ", ".join(str(v) for v in chunk) + ",")
    lines.append("];")
    lines.append("")


