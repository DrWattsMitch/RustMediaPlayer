# Usage: python3 tools/gen_h264_tables.py path/to/openh264/codec > src/codecs/h264/tables.rs
# OpenH264: https://github.com/cisco/openh264 (BSD-2-Clause, Apache-2.0 compatible).
#
# Converts the normative ISO/IEC 14496-10 tables that OpenH264 carries
# (CABAC context initialisation 9-12..9-33, rangeTabLPS 9-44, state
# transitions 9-45, CAVLC codes 9-5, 9-7..9-10) into Rust constants.
import re, sys, os

root = sys.argv[1]


def load(rel):
    s = open(os.path.join(root, rel)).read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def grab(src, name):
    m = re.search(r'\b' + re.escape(name) + r'\s*((?:\[[^\]]*\])*)\s*(?:,\s*\d+\s*\))?\s*=\s*\{', src)
    assert m, name
    i = m.end()
    depth = 1
    while depth:
        c = src[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    body = src[m.end():i - 1].replace('CTX_NA', '0')
    return [int(t, 0) for t in re.split(r'[\s,{}]+', body) if t.strip()]


common = load('common/src/common_tables.cpp')
enc = load('encoder/core/src/encoder_data_tables.cpp')

out = [
    "// Generated by tools/gen_h264_tables.py from OpenH264",
    "// (https://github.com/cisco/openh264, BSD-2-Clause). These are normative",
    "// ISO/IEC 14496-10 tables. Do not edit by hand.",
    "",
]

ctx = grab(common, 'g_kiCabacGlobalContextIdx')
assert len(ctx) == 460 * 4 * 2
out.append("/// CABAC `(m, n)` initialisation per context, for I slices and")
out.append("/// `cabac_init_idc` 0-2 (Tables 9-12 to 9-33; contexts 0-459).")
out.append("pub static CABAC_INIT: [[(i8, i8); 4]; 460] = [")
for i in range(460):
    v = ctx[i * 8:(i + 1) * 8]
    out.append("\t[" + ", ".join("(%d, %d)" % (v[2 * k], v[2 * k + 1]) for k in range(4)) + "],")
out.append("];")
out.append("")

lps = grab(common, 'g_kuiCabacRangeLps')
assert len(lps) == 256
out.append("/// `rangeTabLPS[pStateIdx][qCodIRangeIdx]` (Table 9-44).")
out.append("pub static RANGE_LPS: [[u8; 4]; 64] = [")
for i in range(64):
    out.append("\t[%s]," % ", ".join(str(x) for x in lps[i * 4:i * 4 + 4]))
out.append("];")
out.append("")

trans = grab(common, 'g_kuiStateTransTable')
assert len(trans) == 128
out.append("/// `transIdxLPS` and `transIdxMPS` per state (Table 9-45).")
out.append("pub static TRANS_IDX: [(u8, u8); 64] = [")
for i in range(0, 64, 8):
    out.append("\t" + " ".join("(%d, %d)," % (trans[2 * j], trans[2 * j + 1]) for j in range(i, i + 8)))
out.append("];")
out.append("")

# CAVLC codes: tables of (code, length) indexed as in the spec.
tok = grab(enc, 'g_kuiVlcCoeffToken')
assert len(tok) == 5 * 17 * 4 * 2
out.append("/// `coeff_token` codes `(code, len)` per table (0 <= nC < 2, 2 <= nC < 4,")
out.append("/// 4 <= nC < 8, 8 <= nC, chroma DC nC = -1), indexed")
out.append("/// `[total_coeff][trailing_ones]`; length 0 = no code (Table 9-5).")
out.append("pub static COEFF_TOKEN: [[[(u8, u8); 4]; 17]; 5] = [")
for t in range(5):
    out.append("\t[")
    for tc in range(17):
        base = ((t * 17) + tc) * 8
        v = tok[base:base + 8]
        out.append("\t\t[" + ", ".join("(%d, %d)" % (v[2 * k], v[2 * k + 1]) for k in range(4)) + "],")
    out.append("\t],")
out.append("];")
out.append("")

tz = grab(enc, 'g_kuiVlcTotalZeros')
assert len(tz) == 16 * 16 * 2
out.append("/// `total_zeros` codes for 4x4 blocks, `[total_coeff][total_zeros]` (Tables 9-7, 9-8).")
out.append("pub static TOTAL_ZEROS: [[(u8, u8); 16]; 16] = [")
for tc in range(16):
    v = tz[tc * 32:(tc + 1) * 32]
    out.append("\t[" + ", ".join("(%d, %d)" % (v[2 * k], v[2 * k + 1]) for k in range(16)) + "],")
out.append("];")
out.append("")

tzc = grab(enc, 'g_kuiVlcTotalZerosChromaDc')
assert len(tzc) == 4 * 4 * 2
out.append("/// `total_zeros` codes for 4:2:0 chroma DC, `[total_coeff][total_zeros]` (Table 9-9a).")
out.append("pub static TOTAL_ZEROS_CHROMA_DC: [[(u8, u8); 4]; 4] = [")
for tc in range(4):
    v = tzc[tc * 8:(tc + 1) * 8]
    out.append("\t[" + ", ".join("(%d, %d)" % (v[2 * k], v[2 * k + 1]) for k in range(4)) + "],")
out.append("];")
out.append("")

rb = grab(enc, 'g_kuiVlcRunBefore')
assert len(rb) == 8 * 15 * 2
out.append("/// `run_before` codes, `[min(zeros_left, 7)][run_before]` (Table 9-10).")
out.append("pub static RUN_BEFORE: [[(u8, u8); 15]; 8] = [")
for zl in range(8):
    v = rb[zl * 30:(zl + 1) * 30]
    out.append("\t[" + ", ".join("(%d, %d)" % (v[2 * k], v[2 * k + 1]) for k in range(15)) + "],")
out.append("];")
out.append("")

d4 = grab(common, 'g_kuiDequantScaling4x4Default')
d8 = grab(common, 'g_kuiDequantScaling8x8Default')
assert len(d4) == 32 and len(d8) == 128
out.append("/// Default scaling lists in raster order: `[intra, inter]` (Tables 7-3, 7-4).")
out.append("pub static DEFAULT_SCALING_4X4: [[u8; 16]; 2] = [")
for i in range(2):
    out.append("\t[%s]," % ", ".join(str(x) for x in d4[i * 16:(i + 1) * 16]))
out.append("];")
out.append("pub static DEFAULT_SCALING_8X8: [[u8; 64]; 2] = [")
for i in range(2):
    out.append("\t[%s]," % ", ".join(str(x) for x in d8[i * 64:(i + 1) * 64]))
out.append("];")

print("\n".join(out))
