# Usage: python3 tools/gen_ac3_tables.py path/to/ffmpeg/libavcodec > src/codecs/ac3/tables.rs && cargo fmt
#
# Extracts the normative ATSC A/52 (AC-3) and A/52 Annex E (E-AC-3) tables
# (frame sizes, bit allocation tables, hearing threshold, log-addition table,
# AHT vector-quantisation codebooks, ...) from FFmpeg's copies of them and
# writes them as Rust arrays. The values are the standard's; only the layout
# is RMP's.
import os, re, sys

root = sys.argv[1]


def load(name):
    s = open(os.path.join(root, name)).read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    return re.sub(r'//[^\n]*', '', s)


src = load('ac3tab.c') + load('ac3.c') + load('eac3_data.c') + load('ac3dec_data.c')


def grab(name):
    m = re.search(r'\b' + name + r'\s*((?:\[[^\]]*\])*)\s*=\s*\{', src)
    assert m, name
    i = m.end()
    depth = 1
    rows = []
    while depth:
        c = src[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    body = src[m.end():i - 1]
    return body


def flat(name):
    return [int(t, 0) for t in re.split(r'[\s,{}]+', grab(name)) if t.strip()]


def rows(name, width):
    body = grab(name)
    out = []
    for r in re.findall(r'\{([^{}]*)\}', body):
        vals = [int(t, 0) for t in re.split(r'[\s,]+', r) if t.strip()]
        out.append(vals + [0] * (width - len(vals)))
    return out


def arr(vals, per=16):
    lines = []
    for i in range(0, len(vals), per):
        lines.append('\t' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    return '\n'.join(lines)


out = [
    '// Generated by tools/gen_ac3_tables.py: the normative ATSC A/52 and',
    '// A/52 Annex E tables, extracted from FFmpeg\'s libavcodec copies.',
    '// Do not edit by hand.',
    '',
]


def emit(doc, name, ty, vals, per=16):
    out.append('/// ' + doc)
    out.append('pub static %s: [%s; %d] = [' % (name, ty, len(vals)))
    out.append(arr(vals, per))
    out.append('];')
    out.append('')


fs = rows('ff_ac3_frame_size_tab', 3)
out.append('/// Frame size in 16-bit words by `frmsizecod` and `fscod` (Table 5.18).')
out.append('pub static FRAME_SIZE_WORDS: [[u16; 3]; 38] = [')
for r in fs:
    out.append('\t[%s],' % ', '.join(map(str, r)))
out.append('];')
out.append('')

emit('First bin of each of the 50 critical bands, plus the end bin.', 'BAND_START', 'u8',
     flat('ff_ac3_band_start_tab'))
emit('Critical band of each bin below 253.', 'BIN_TO_BAND', 'u8', flat('ff_ac3_bin_to_band_tab'), 24)
emit('Log-addition table (Table 7.14).', 'LOG_ADD', 'u8', flat('ac3_log_add_tab'), 20)

ht = rows('ac3_hearing_threshold_tab', 3)
out.append('/// Hearing threshold by band and `fscod` (Table 7.15).')
out.append('pub static HEARING_THRESHOLD: [[u16; 3]; 50] = [')
for r in ht:
    out.append('\t[%s],' % ', '.join(str(v) for v in r))
out.append('];')
out.append('')

emit('Bit allocation pointer by masked PSD address (Table 7.16).', 'BAP', 'u8', flat('ff_ac3_bap_tab'))
emit('High-efficiency bap for AHT channels (Table E3.1).', 'HEBAP', 'u8', flat('ff_eac3_hebap_tab'))
emit('Mantissa bits per hebap (Table E3.2).', 'BITS_VS_HEBAP', 'u8', flat('ff_eac3_bits_vs_hebap'), 20)
emit('GAQ remap scale for Gk=1 (Table E3.6), by hebap-8.', 'GAQ_REMAP_1', 'i16', flat('ff_eac3_gaq_remap_1'))

for nm, rust in (('ff_eac3_gaq_remap_2_4_a', 'GAQ_REMAP_2_4_A'), ('ff_eac3_gaq_remap_2_4_b', 'GAQ_REMAP_2_4_B')):
    r = rows(nm, 2)
    out.append('/// Large-mantissa GAQ remap (Table E3.6), `[hebap-8][Gk=2,4]`.')
    out.append('pub static %s: [[i16; 2]; 9] = [' % rust)
    for v in r:
        out.append('\t[%d, %d],' % tuple(v))
    out.append('];')
    out.append('')

sizes = {1: 4, 2: 8, 3: 16, 4: 32, 5: 128, 6: 256, 7: 512}
for h, n in sizes.items():
    r = rows('vq_hebap%d' % h, 6)
    r += [[0] * 6] * (n - len(r))
    assert len(r) == n, (h, len(r))
    out.append('/// AHT vector-quantisation codebook for hebap %d (Table E4.%d).' % (h, h))
    out.append('pub static VQ_HEBAP%d: [[i16; 6]; %d] = [' % (h, n))
    for v in r:
        out.append('\t[%s],' % ', '.join(str(x) for x in v))
    out.append('];')
    out.append('')

body = grab('ff_eac3_frm_expstr')
names = {'EXP_REUSE': 0, 'EXP_D15': 1, 'EXP_D25': 2, 'EXP_D45': 3}
out.append('/// Frame exponent strategy combinations (Table E2.14).')
out.append('pub static FRAME_EXP_STRATEGY: [[u8; 6]; 32] = [')
for r in re.findall(r'\{([^{}]*)\}', body):
    vals = [names[t] for t in re.split(r'[\s,]+', r) if t.strip()]
    out.append('\t[%s],' % ', '.join(map(str, vals)))
out.append('];')
out.append('')

print('\n'.join(out))
