# Usage: python3 tools/gen_mp3_tables.py path/to/minimp3.h > src/codecs/mp3/tables.rs
# minimp3: https://github.com/lieff/minimp3 (CC0 / public domain).
# Converts the numeric tables of minimp3 (CC0) into Rust constants.
import re, sys
src = open(sys.argv[1]).read()
def grab(name):
    m = re.search(r'static const (\w+) ' + name + r'((?:\[[^\]]*\])*)\s*=\s*\{', src)
    assert m, name
    i = m.end(); depth = 1
    while depth:
        c = src[i]
        depth += c == '{'; depth -= c == '}'
        i += 1
    body = src[m.end():i-1]
    dims = [d for d in re.findall(r'\[([^\]]*)\]', m.group(2))]
    return m.group(1), dims, body
def nums(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [t.strip() for t in body.replace('{',',').replace('}',',').split(',') if t.strip()]
def fmt_float(t):
    t = t.rstrip('fF')
    if t.startswith('-'): sign='-'; t=t[1:]
    else: sign=''
    if '.' not in t and 'e' not in t: t += '.0'
    if t.startswith('.'): t='0'+t
    return sign+t
def rows(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [nums(r) for r in re.findall(r'\{([^{}]*)\}', body)]
rt = {'uint8_t':'u8','int16_t':'i16','float':'f32','unsigned':'u32'}
out = ["// Generated by tools/gen_mp3_tables.py from minimp3 (https://github.com/lieff/minimp3),",
       "// which is dedicated to the public domain (CC0). These are the standard",
       "// ISO/IEC 11172-3 / 13818-3 Layer III constants in the compact layout used",
       "// by the decoder in this module. Do not edit by hand.",
       "#![allow(clippy::excessive_precision, clippy::approx_constant)]", ""]
def emit(cname, rname, pad_cols=None):
    ty, dims, body = grab(cname)
    t = rt[ty]
    conv = fmt_float if t == 'f32' else (lambda x: x)
    if len(dims) == 2 and dims[0] and dims[1] and pad_cols is not False:
        rs = rows(body)
        cols = int(dims[1]) if dims[1].isdigit() else eval(dims[1])
        assert all(len(r) <= cols for r in rs), (cname, [len(r) for r in rs])
        rs = [r + ['0']*(cols-len(r)) for r in rs]
        out.append(f"pub const {rname}: [[{t}; {cols}]; {len(rs)}] = [")
        for r in rs:
            out.append("\t[" + ", ".join(conv(x) for x in r) + "],")
        out.append("];")
    else:
        vals = nums(body)
        out.append(f"pub const {rname}: [{t}; {len(vals)}] = [")
        for k in range(0, len(vals), 16):
            out.append("\t" + ", ".join(conv(x) for x in vals[k:k+16]) + ",")
        out.append("];")
    out.append("")
for c, r in [('g_scf_long','SCF_LONG'),('g_scf_short','SCF_SHORT'),('g_scf_mixed','SCF_MIXED'),
             ('g_scf_partitions','SCF_PARTITIONS'),('g_scfc_decode','SCFC_DECODE'),('g_mod','SCF_MOD'),
             ('g_preamp','PREAMP'),('g_expfrac','EXPFRAC'),('g_pow43','POW43'),('tabs','HUFF_TABS'),
             ('tab32','HUFF_COUNT1_A'),('tab33','HUFF_COUNT1_B'),('tabindex','HUFF_TAB_INDEX'),
             ('g_linbits','LINBITS'),('g_pan','PAN'),('g_aa','ANTIALIAS'),('g_twid9','TWID9'),
             ('g_twid3','TWID3'),('g_mdct_window','MDCT_WINDOW'),('g_sec','DCT_SEC'),('g_win','SYNTH_WIN')]:
    emit(c, r)
print("\n".join(out))
