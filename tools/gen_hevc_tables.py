# Usage: python3 tools/gen_hevc_tables.py path/to/ffmpeg/libavcodec/hevc > src/codecs/hevc/tables.rs && cargo fmt
#
# Extracts the CABAC context initialisation values of ITU-T H.265 (Tables
# 9-5 to 9-37, in FFmpeg's flat per-init-type layout) and emits them with the
# context index offset of every syntax element. The values are the standard's.
import os, re, sys

src = open(os.path.join(sys.argv[1], 'cabac.c')).read()
elems = re.findall(r'ELEM\((\w+),\s*(\d+)\)', src)
body = src[src.index('init_values[3][HEVC_CONTEXTS] = {'):]
body = body[body.index('{') + 1:]
groups, depth, cur = [], 0, ''
for ch in body:
    if ch == '{':
        depth += 1
        cur = ''
        continue
    if ch == '}':
        if depth == 0:
            break
        depth -= 1
        groups.append(cur)
        continue
    cur += ch
vals = []
for g in groups:
    g = re.sub(r'//[^\n]*', '', g).replace('CNU', '154')
    vals.append([int(t) for t in re.split(r'[\s,]+', g) if t.strip()])
total = sum(int(n) for _, n in elems)
assert len(vals) == 3 and all(len(v) == total for v in vals), (len(vals), [len(v) for v in vals], total)

out = ['// Generated by tools/gen_hevc_tables.py from the H.265 CABAC initValue',
       '// tables (FFmpeg\'s `hevc/cabac.c` layout). Do not edit by hand.', '',
       '// Offsets of syntax elements this decoder does not use (range',
       '// extensions, bypass-coded elements) are kept to document the layout.',
       '#![allow(dead_code)]', '']
off = 0
out.append('/// Context index offset of each syntax element.')
for name, n in elems:
    out.append('pub const %s: usize = %d;' % (name, off))
    off += int(n)
out.append('/// Total number of CABAC contexts.')
out.append('pub const NUM_CTX: usize = %d;' % total)
out.append('')
out.append('/// initValue per context, indexed by initType (0: I, 1: P, 2: B).')
out.append('pub static INIT_VALUES: [[u8; NUM_CTX]; 3] = [')
for v in vals:
    out.append('\t[')
    for i in range(0, len(v), 20):
        out.append('\t\t' + ', '.join(map(str, v[i:i + 20])) + ',')
    out.append('\t],')
out.append('];')
print('\n'.join(out))
