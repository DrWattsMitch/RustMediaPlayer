#
# Converts the normative ISO/IEC 14496-3 Huffman codebooks (Tables 4.A.1-4.A.12)
# and scalefactor-band offset tables (Tables 4.129-4.147) from vo-aacenc's
# encoder tables into the decoder-friendly layout used by `codecs::aac`.
import re, sys

src = open(sys.argv[1]).read()
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
src = re.sub(r'//[^\n]*', '', src)


def grab(name):
    m = re.search(r'const\s+\w+\s+' + name + r'\s*((?:\[[^\]]*\])*)\s*=\s*\{', src)
    assert m, name
    i = m.end()
    depth = 1
    while depth:
        c = src[i]
        depth += c == '{'
        depth -= c == '}'
        i += 1
    body = src[m.end():i - 1]
    return [int(t, 0) for t in re.split(r'[\s,{}]+', body) if t.strip()]


# Per codebook: (code table, length table, which byte of a packed length table).
books = {
    1: ('huff_ctab1', 'huff_ltab1_2', 8), 2: ('huff_ctab2', 'huff_ltab1_2', 0),
    3: ('huff_ctab3', 'huff_ltab3_4', 8), 4: ('huff_ctab4', 'huff_ltab3_4', 0),
    5: ('huff_ctab5', 'huff_ltab5_6', 8), 6: ('huff_ctab6', 'huff_ltab5_6', 0),
    7: ('huff_ctab7', 'huff_ltab7_8', 8), 8: ('huff_ctab8', 'huff_ltab7_8', 0),
    9: ('huff_ctab9', 'huff_ltab9_10', 8), 10: ('huff_ctab10', 'huff_ltab9_10', 0),
    11: ('huff_ctab11', 'huff_ltab11', None),
}


def check_prefix_free(pairs, name):
    total = sum(2.0 ** -l for _, l in pairs)
    assert abs(total - 1.0) < 1e-12, (name, total)
    seen = set()
    for code, length in pairs:
        key = format(code, '0%db' % length)
        for other in seen:
            assert not key.startswith(other) and not other.startswith(key), name
        seen.add(key)


out = [
    "// Generated by tools/gen_aac_tables.py from vo-aacenc",
    "// (https://github.com/mstorsjo/vo-aacenc, Apache-2.0). These are the normative",
    "// ISO/IEC 14496-3 Huffman codebooks and scalefactor-band tables. Do not edit",
    "// by hand.",
    "",
]

out.append("/// Spectral codebooks 1-11 as `(codeword, length)`, in codebook index order")
out.append("/// (ISO/IEC 14496-3 Tables 4.A.2-4.A.12).")
out.append("pub static SPECTRUM_CODES: [&[(u32, u8)]; 11] = [")
for cb in range(1, 12):
    cname, lname, shift = books[cb]
    codes = grab(cname)
    lens = grab(lname)
    if shift is not None:
        lens = [(l >> shift) & 0xff for l in lens]
    assert len(codes) == len(lens), cb
    pairs = list(zip(codes, lens))
    check_prefix_free(pairs, 'cb%d' % cb)
    out.append("\t&[")
    for i in range(0, len(pairs), 8):
        out.append("\t\t" + " ".join("(0x%x, %d)," % p for p in pairs[i:i + 8]))
    out.append("\t],")
out.append("];")
out.append("")

codes = grab('huff_ctabscf')
lens = grab('huff_ltabscf')
pairs = list(zip(codes, lens))
assert len(pairs) == 121
check_prefix_free(pairs, 'scf')
out.append("/// Scalefactor codebook as `(codeword, length)`; index 60 is a difference of 0")
out.append("/// (ISO/IEC 14496-3 Table 4.A.1).")
out.append("pub static SCALEFACTOR_CODES: [(u32, u8); 121] = [")
for i in range(0, len(pairs), 8):
    out.append("\t" + " ".join("(0x%x, %d)," % p for p in pairs[i:i + 8]))
out.append("];")
out.append("")

short_tab = grab('sfBandTabShort')
long_tab = grab('sfBandTabLong')
short_off = grab('sfBandTabShortOffset')
long_off = grab('sfBandTabLongOffset')
long_n = grab('sfBandTotalLong')
short_n = grab('sfBandTotalShort')


def emit_offsets(name, tab, offs, counts, total):
    out.append("/// Scalefactor-band start offsets per sampling-frequency index (0 = 96 kHz")
    out.append("/// ... 11 = 8 kHz), terminated by the window length.")
    out.append("pub static %s: [&[u16]; 12] = [" % name)
    for idx in range(12):
        start = offs[idx]
        vals = tab[start:start + counts[idx] + 1]
        assert vals[0] == 0 and vals[-1] == total, (name, idx, vals)
        out.append("\t&[" + ", ".join(str(v) for v in vals) + "],")
    out.append("];")
    out.append("")


emit_offsets("SWB_OFFSET_LONG", long_tab, long_off, long_n, 1024)
emit_offsets("SWB_OFFSET_SHORT", short_tab, short_off, short_n, 128)

print("\n".join(out))
