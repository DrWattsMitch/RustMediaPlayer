# Usage: python3 tools/gen_vp9_tables.py path/to/libvpx > src/codecs/vp9/tables.rs
# libvpx: https://github.com/webmproject/libvpx (BSD-3-Clause, Apache-2.0
# compatible).
#
# Converts the normative tables of the VP9 bitstream specification that
# libvpx carries (default and key-frame probabilities, coefficient
# probabilities and the Pareto model, scans with their context neighbours,
# coefficient bands, quantizer lookups and the sub-pixel filters) into Rust
# constants.
import os
import re
import sys

root = sys.argv[1]


def load(rel):
    s = open(os.path.join(root, rel)).read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def initializer(src, name):
    """The `{ ... }` initializer of `name`, as nested Python lists."""
    m = re.search(r'\b' + re.escape(name) + r'\s*(?:\[[^\]]*\]\s*)*\)?\s*=\s*\{', src)
    assert m, name
    i = m.end()
    stack = [[]]
    token = ''
    while stack:
        c = src[i]
        i += 1
        if c == '{':
            stack.append([])
        elif c in ',}':
            if token.strip():
                stack[-1].append(int(token.strip()))
            token = ''
            if c == '}':
                done = stack.pop()
                if not stack:
                    return done
                stack[-1].append(done)
        elif not c.isspace():
            token += c
    raise AssertionError(name)


def shape(value, dims):
    """Pads `value` with zeros (C initializer semantics) to `dims`."""
    if not dims:
        assert not isinstance(value, list)
        return value
    if not isinstance(value, list):
        value = [value]
    # A flat initializer for a multi-dimensional array fills it in order.
    if len(dims) > 1 and all(not isinstance(v, list) for v in value):
        size = 1
        for d in dims[1:]:
            size *= d
        value = [value[k:k + size] for k in range(0, len(value), size)]
    assert len(value) <= dims[0], (len(value), dims)
    out = [shape(v, dims[1:]) for v in value]
    while len(out) < dims[0]:
        out.append(shape([], dims[1:]) if len(dims) > 1 else 0)
    return out


def flatten(v):
    if isinstance(v, list):
        for x in v:
            yield from flatten(x)
    else:
        yield v


def rust_type(base, dims):
    t = base
    for d in reversed(dims):
        t = '[%s; %d]' % (t, d)
    return t


def emit(doc, rust, base, dims, value):
    value = shape(value, dims)
    print('/// %s' % doc)
    print('pub static %s: %s = %s;' % (rust, rust_type(base, dims), literal(value)))
    print()


def literal(v):
    if isinstance(v, list):
        if v and not isinstance(v[0], list):
            return '[' + ', '.join(str(x) for x in v) + ']'
        return '[' + ', '.join(literal(x) for x in v) + ']'
    return str(v)


mode = load('vp9/common/vp9_entropymode.c')
entropy = load('vp9/common/vp9_entropy.c')
scan = load('vp9/common/vp9_scan.c')
quant = load('vp9/common/vp9_quant_common.c')
filt = load('vp9/common/vp9_filter.c')

print('// Generated by tools/gen_vp9_tables.py from libvpx')
print('// (https://github.com/webmproject/libvpx, BSD-3-Clause). These are the')
print('// normative tables of the VP9 bitstream specification. Do not edit by hand.')
print('#![allow(clippy::unreadable_literal, clippy::type_complexity)]')
print('#[rustfmt::skip]')
print('mod data {')
print()

emit('Key-frame luma mode probabilities `[above][left][node]` (`vp9_kf_y_mode_prob`).',
     'KF_Y_MODE_PROBS', 'u8', [10, 10, 9], initializer(mode, 'vp9_kf_y_mode_prob'))
emit('Key-frame chroma mode probabilities `[luma mode][node]` (`vp9_kf_uv_mode_prob`).',
     'KF_UV_MODE_PROBS', 'u8', [10, 9], initializer(mode, 'vp9_kf_uv_mode_prob'))
emit('Inter-frame luma mode probabilities by block size group (`default_if_y_probs`).',
     'DEFAULT_Y_MODE_PROBS', 'u8', [4, 9], initializer(mode, 'default_if_y_probs'))
emit('Inter-frame chroma mode probabilities (`default_if_uv_probs`).',
     'DEFAULT_UV_MODE_PROBS', 'u8', [10, 9], initializer(mode, 'default_if_uv_probs'))
emit('Key-frame partition probabilities, 8x8 contexts first (`vp9_kf_partition_probs`).',
     'KF_PARTITION_PROBS', 'u8', [16, 3], initializer(mode, 'vp9_kf_partition_probs'))
emit('Inter-frame partition probabilities (`default_partition_probs`).',
     'DEFAULT_PARTITION_PROBS', 'u8', [16, 3], initializer(mode, 'default_partition_probs'))
emit('Inter mode probabilities by mode context (`default_inter_mode_probs`).',
     'DEFAULT_INTER_MODE_PROBS', 'u8', [7, 3], initializer(mode, 'default_inter_mode_probs'))
emit('`default_intra_inter_p`.', 'DEFAULT_INTRA_INTER_PROBS', 'u8', [4],
     initializer(mode, 'default_intra_inter_p'))
emit('`default_comp_inter_p`.', 'DEFAULT_COMP_INTER_PROBS', 'u8', [5],
     initializer(mode, 'default_comp_inter_p'))
emit('`default_comp_ref_p`.', 'DEFAULT_COMP_REF_PROBS', 'u8', [5],
     initializer(mode, 'default_comp_ref_p'))
emit('`default_single_ref_p`.', 'DEFAULT_SINGLE_REF_PROBS', 'u8', [5, 2],
     initializer(mode, 'default_single_ref_p'))
emit('`default_skip_probs`.', 'DEFAULT_SKIP_PROBS', 'u8', [3],
     initializer(mode, 'default_skip_probs'))
emit('`default_switchable_interp_prob`.', 'DEFAULT_INTERP_FILTER_PROBS', 'u8', [4, 2],
     initializer(mode, 'default_switchable_interp_prob'))

coef = [shape(initializer(entropy, 'default_coef_probs_%s' % s), [2, 2, 6, 6, 3])
        for s in ('4x4', '8x8', '16x16', '32x32')]
emit('Coefficient probabilities `[tx size][plane type][ref][band][context][node]`\n'
     '/// (`default_coef_probs_*`; band 0 has 3 contexts, the rest are zero).',
     'DEFAULT_COEF_PROBS', 'u8', [4, 2, 2, 6, 6, 3], coef)
emit('Pareto model: the 8 remaining token probabilities for each pivot\n'
     '/// probability 1..=255 (`vp9_pareto8_full`).',
     'PARETO8', 'u8', [255, 8], initializer(entropy, 'vp9_pareto8_full'))
emit('Coefficient band of each scan position, 4x4 (`vp9_coefband_trans_4x4`).',
     'COEFBAND_4X4', 'u8', [16], initializer(entropy, 'vp9_coefband_trans_4x4'))
emit('Coefficient band of each scan position, 8x8 and larger\n'
     '/// (`vp9_coefband_trans_8x8plus`).',
     'COEFBAND_8X8PLUS', 'u8', [1024], initializer(entropy, 'vp9_coefband_trans_8x8plus'))

for size, n in (('4x4', 16), ('8x8', 64), ('16x16', 256), ('32x32', 1024)):
    kinds = ('default', 'col', 'row') if size != '32x32' else ('default',)
    for kind in kinds:
        emit('`%s_scan_%s`.' % (kind, size), '%s_SCAN_%s' % (kind.upper(), size.upper()),
             'u16', [n], initializer(scan, '%s_scan_%s' % (kind, size)))
        emit('Context neighbours (above, left) of each scan position\n'
             '/// (`%s_scan_%s_neighbors`).' % (kind, size),
             '%s_SCAN_%s_NEIGHBORS' % (kind.upper(), size.upper()),
             'u16', [n + 1, 2], initializer(scan, '%s_scan_%s_neighbors' % (kind, size)))

emit('DC quantizer by q index for 8, 10 and 12 bits (`dc_qlookup*`).', 'DC_QLOOKUP',
     'i16', [3, 256], [initializer(quant, n) for n in ('dc_qlookup', 'dc_qlookup_10', 'dc_qlookup_12')])
emit('AC quantizer by q index for 8, 10 and 12 bits (`ac_qlookup*`).', 'AC_QLOOKUP',
     'i16', [3, 256], [initializer(quant, n) for n in ('ac_qlookup', 'ac_qlookup_10', 'ac_qlookup_12')])
emit('Sub-pixel filters by interpolation filter (regular, smooth, sharp,\n'
     '/// bilinear) and 1/16 phase (`vp9_filter_kernels`).', 'SUBPEL_FILTERS', 'i16', [4, 16, 8],
     [initializer(filt, n) for n in ('sub_pel_filters_8', 'sub_pel_filters_8lp',
                                     'sub_pel_filters_8s', 'bilinear_filters')])

print('}')
print()
print('pub use data::*;')
