#!/usr/bin/env python3
"""Generates src/codecs/av1/encoder/tables.rs from rav1d's sources.

The AV1 encoder needs the normative default CDFs, scan orders, quantizer
tables, sub-pixel filters and smooth-prediction weights. These are long
tables of numbers; rather than retype them, this script extracts them from
rav1d (the decoder RMP already depends on, BSD-2-Clause) so they are
exactly the ones the decoder uses.

Usage: tools/gen_av1_tables.py <rav1d checkout> > src/codecs/av1/encoder/tables.rs

CDFs are written in rav1d's in-memory form: for an N-symbol CDF, N - 1
values `32768 - cdf[i]` (decreasing) followed by the adaptation counter (0).
"""
import re
import sys


def tokenize(s):
    s = re.sub(r"//[^\n]*", "", s)
    s = re.sub(r"[A-Za-z_][A-Za-z_0-9]*::", "", s)  # paths: keep the last name
    return re.findall(r"[A-Za-z_#][A-Za-z_0-9#]*|-?\d+|[{}\[\]():,]", s)


class P:
    def __init__(self, toks):
        self.t = toks
        self.i = 0

    def peek(self):
        return self.t[self.i]

    def take(self, x=None):
        v = self.t[self.i]
        if x is not None and v != x:
            raise SyntaxError(f"expected {x}, got {v} at {self.i}: {self.t[self.i - 5:self.i + 5]}")
        self.i += 1
        return v

    def value(self):
        t = self.peek()
        if t == "[":
            self.take("[")
            items = []
            while self.peek() != "]":
                items.append(self.value())
                if self.peek() == ",":
                    self.take(",")
            self.take("]")
            return items
        if re.fullmatch(r"-?\d+", t):
            self.take()
            return int(t)
        name = self.take()
        if self.peek() == "(":
            self.take("(")
            v = self.value()
            self.take(")")
            if name.startswith("cdf"):
                return ("cdf", v)
            return v
        if self.peek() == "{":
            self.take("{")
            fields = {}
            while self.peek() != "}":
                key = self.take()
                self.take(":")
                fields[key] = self.value()
                if self.peek() == ",":
                    self.take(",")
            self.take("}")
            return fields
        return name


def static_body(src, name):
    m = re.search(r"static " + name + r"[^=]*=", src)
    start = m.end()
    # Up to the statement's semicolon at nesting level 0.
    depth = 0
    for i in range(start, len(src)):
        c = src[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ";" and depth == 0:
            return src[start:i]
    raise ValueError(name)


def invert(v):
    """A probs array (or nesting of them) to rav1d's stored form."""
    if isinstance(v, list) and v and isinstance(v[0], int):
        return [(32768 - p) & ~32768 for p in v] + [0]
    return [invert(x) for x in v]


def strip(v):
    """Removes the ("cdf", ..) markers, inverting what they wrap."""
    if isinstance(v, tuple) and v[0] == "cdf":
        return invert(v[1])
    if isinstance(v, list):
        return [strip(x) for x in v]
    if isinstance(v, dict):
        return {k: strip(x) for k, x in v.items()}
    return v


def shape(v):
    if isinstance(v, list):
        inner = shape(v[0])
        for x in v[1:]:
            assert shape(x) == inner, "ragged table"
        return [len(v)] + inner
    return []


def rust_type(base, dims):
    t = base
    for d in reversed(dims):
        t = f"[{t}; {d}]"
    return t


def rust_value(v):
    if isinstance(v, list):
        return "[" + ", ".join(rust_value(x) for x in v) + "]"
    return str(v)


def emit(name, base, v, doc):
    print(f"/// {doc}")
    print(f"pub static {name}: {rust_type(base, shape(v))} = {rust_value(v)};")
    print()


def main():
    root = sys.argv[1]
    cdf_src = open(f"{root}/src/cdf.rs").read()
    d = strip(P(tokenize(static_body(cdf_src, "default_cdf"))).value())

    print("//! Tables for the AV1 encoder, generated by `tools/gen_av1_tables.py` from")
    print("//! rav1d (BSD-2-Clause, Copyright © 2018-2021 VideoLAN and dav1d authors,")
    print("//! © 2023 Prossimo / ISRG): default CDFs, scan orders, quantizers, filters.")
    print("//! Do not edit by hand.")
    print("#![allow(clippy::unreadable_literal)]")
    print()

    coef = d["coef"]
    for f in ["eob_bin_16", "eob_bin_32", "eob_bin_64", "eob_bin_128", "eob_bin_256",
              "eob_bin_512", "eob_bin_1024", "eob_base_tok", "base_tok", "br_tok",
              "eob_hi_bit", "skip", "dc_sign"]:
        emit(f"COEF_{f.upper()}", "u16", [c[f] for c in coef],
             f"`coef.{f}` for each quantizer context (`[qctx]...`).")

    m = d["m"]
    uv = m["uv_mode"]
    emit("UV_MODE_NO_CFL", "u16", uv[0], "`m.uv_mode[0]` (CfL not allowed), by luma mode.")
    emit("UV_MODE_CFL", "u16", uv[1], "`m.uv_mode[1]` (CfL allowed), by luma mode.")
    part = m["partition"]
    emit("PARTITION_64", "u16", part[1], "`m.partition[BL_64X64]`, by context.")
    emit("PARTITION_32", "u16", part[2], "`m.partition[BL_32X32]`.")
    emit("PARTITION_16", "u16", part[3], "`m.partition[BL_16X16]`.")
    emit("PARTITION_8", "u16", part[4], "`m.partition[BL_8X8]`.")
    for f in ["txtp_intra1", "txtp_intra2", "txtp_inter3", "angle_delta", "txsz", "txpart", "skip"]:
        emit(f"M_{f.upper()}", "u16", m[f], f"`m.{f}`.")

    mi = d["mi"]
    for f in ["y_mode", "newmv_mode", "globalmv_mode", "refmv_mode", "drl_bit", "intra", "ref"]:
        emit(f"MI_{f.upper().replace('#', '')}", "u16", mi[f if f != "ref" else "r#ref"], f"`mi.{f}`.")

    mv = d["mv"]
    comp = mv["comp"]
    emit("MV_JOINT", "u16", mv["joint"], "`mv.joint`.")
    for f in ["classes", "class_0_fp", "class_n_fp", "class_0_hp", "class_n_hp", "class_0",
              "class_n", "sign"]:
        emit(f"MV_{f.upper()}", "u16", comp[f], f"`mv.comp.{f}`.")
    emit("KF_Y_MODE", "u16", d["kfym"], "`kfym`, by above and left mode context.")

    scan_src = open(f"{root}/src/scan.rs").read()
    for n in ["4x4", "8x8", "16x16", "32x32"]:
        v = P(tokenize(static_body(scan_src, f"scan_{n}"))).value()
        emit(f"SCAN_{n.upper()}", "u16", v, f"Scan of {n} transforms (`rc = x * h + y`).")

    dq_src = open(f"{root}/src/dequant_tables.rs").read()
    dq = P(tokenize(static_body(dq_src, "dav1d_dq_tbl"))).value()
    emit("DQ_8BIT", "u16", dq[0], "8-bit quantizers `[qindex][dc, ac]`.")

    tab_src = open(f"{root}/src/tables.rs").read()
    emit("SUBPEL_FILTERS", "i8", P(tokenize(static_body(tab_src, "dav1d_mc_subpel_filters"))).value(),
         "Sub-pixel filters `[regular, smooth, sharp, regular 4-tap, smooth 4-tap, bilinear][phase - 1]`, halved.")
    emit("SM_WEIGHTS", "u8", P(tokenize(static_body(tab_src, "dav1d_sm_weights"))).value(),
         "Smooth prediction weights, `[size..2 * size]` for each size.")
    emit("DR_INTRA_DERIVATIVE", "u16",
         P(tokenize(static_body(tab_src, "dav1d_dr_intra_derivative"))).value(),
         "Directional prediction steps by `angle >> 1`.")


main()
