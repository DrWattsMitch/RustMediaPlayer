# Usage: python3 tools/gen_sbr_tables.py path/to/ffmpeg/libavcodec > src/codecs/aac/sbr_tables.rs && cargo fmt
#
# Extracts the normative ISO/IEC 14496-3 SBR and Parametric Stereo tables
# (QMF prototype window, SBR noise table, start-frequency offsets, the SBR and
# PS Huffman codebooks, the PS k->i band maps) from FFmpeg's copies and
# writes them as Rust arrays. The values are the standard's.
import os, re, sys

root = sys.argv[1]


def load(name):
    s = open(os.path.join(root, name)).read()
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    # Architecture-specific padding rows (RISC-V vector loads).
    s = re.sub(r'#if ARCH_RISCV.*?#endif', '', s, flags=re.S)
    s = re.sub(r'Q31\(([^)]*)\)', r'\1', s)
    return re.sub(r'-\s+', '-', s)


def body(src, name):
    m = re.search(r'\b' + name + r'\s*\)*\s*((?:\[[^\]]*\])*)\s*=\s*\{', src)
    assert m, name
    i, depth = m.end(), 1
    while depth:
        depth += src[i] == '{'
        depth -= src[i] == '}'
        i += 1
    return src[m.end():i - 1]


def nums(text, conv=int):
    out = []
    for t in re.split(r'[\s,{}]+', text):
        t = t.strip()
        if not t or t.startswith('#'):
            continue
        out.append(conv(t.rstrip('f')) if conv is float else int(t, 0))
    return out


sbrdata = load('aacsbrdata.h')
dsp = load('sbrdsp_template.c')
tab = load('aac/aacdec_tab.c')
ps = load('aacpsdata.c')

out = [
    '// Generated by tools/gen_sbr_tables.py: the normative ISO/IEC 14496-3',
    '// SBR and Parametric Stereo tables, extracted from FFmpeg\'s libavcodec',
    '// copies. Do not edit by hand.',
    '',
    '// The values are FFmpeg\'s, digit for digit.',
    '#![allow(clippy::excessive_precision)]',
    '',
]


def emit(doc, name, ty, vals, per=8, fmt=str):
    out.append('/// ' + doc)
    out.append('pub static %s: [%s; %d] = [' % (name, ty, len(vals)))
    for i in range(0, len(vals), per):
        out.append('\t' + ', '.join(fmt(v) for v in vals[i:i + per]) + ',')
    out.append('];')
    out.append('')


ffmt = lambda v: repr(float(v))

off = nums(body(sbrdata, 'sbr_offset'))
assert len(off) == 96
out.append('/// Start-frequency offsets by SBR rate class (Table 4.82).')
out.append('pub static SBR_OFFSET: [[i8; 16]; 6] = [')
for i in range(6):
    out.append('\t[%s],' % ', '.join(map(str, off[16 * i:16 * i + 16])))
out.append('];')
out.append('')

ds = nums(body(sbrdata, 'sbr_qmf_window_ds'), float)
us = nums(body(sbrdata, 'sbr_qmf_window_us'), float)
assert len(ds) == 320 and len(us) == 640
emit('QMF prototype window, downsampled (every other coefficient).', 'QMF_WINDOW_DS', 'f32', ds, 4, ffmt)
emit('QMF prototype window (Table 4.A.89).', 'QMF_WINDOW_US', 'f32', us, 4, ffmt)

noise = nums(body(dsp, 'ff_sbr_noise_table'), float)
assert len(noise) == 2 * 520, len(noise)
out.append('/// SBR noise table V (Table 4.A.88), first 8 entries repeated at the end.')
out.append('pub static NOISE_TABLE: [[f32; 2]; 520] = [')
for i in range(0, len(noise), 2):
    out.append('\t[%s, %s],' % (ffmt(noise[i]), ffmt(noise[i + 1])))
out.append('];')
out.append('')

h = nums(body(tab, 'sbr_huffman_tab'))
emit('SBR Huffman tables as `(symbol, length)` in code order (Tables 4.A.78-87).',
     'SBR_HUFFMAN', '(u8, u8)', [(h[i], h[i + 1]) for i in range(0, len(h), 2)], 8, lambda p: '(%d, %d)' % p)
emit('Codes per SBR Huffman table.', 'SBR_HUFFMAN_SIZES', 'u8', nums(body(tab, 'sbr_huffman_nb_codes')), 10)
emit('Symbol offsets of the SBR Huffman tables.', 'SBR_HUFFMAN_OFFSETS', 'i8', nums(body(tab, 'sbr_vlc_offsets')), 10)

h = nums(body(ps, 'aacps_huff_tabs'))
emit('PS Huffman tables as `(symbol, length)` in code order (Tables 8.A.18-27).',
     'PS_HUFFMAN', '(u8, u8)', [(h[i], h[i + 1]) for i in range(0, len(h), 2)], 8, lambda p: '(%d, %d)' % p)
emit('Codes per PS Huffman table.', 'PS_HUFFMAN_SIZES', 'u8', nums(body(ps, 'huff_sizes')), 10)
emit('Symbol offsets of the PS Huffman tables.', 'PS_HUFFMAN_OFFSETS', 'i8', nums(body(ps, 'huff_offset')), 10)
emit('Hybrid band to parameter band, 20-band mode (Table 8.48).', 'K_TO_I_20', 'u8', nums(body(ps, 'ff_k_to_i_20')), 20)
emit('Hybrid band to parameter band, 34-band mode (Table 8.49).', 'K_TO_I_34', 'u8', nums(body(ps, 'ff_k_to_i_34')), 20)

print('\n'.join(out))
